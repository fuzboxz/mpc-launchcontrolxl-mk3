#!/usr/bin/env lua5.4
-- gen-manual.lua -- render docs/MANUAL.md from the controller script itself.
--
-- The manual is GENERATED: the single source of truth is the ACTIONS table (and
-- the palette) inside script/LaunchControlXL3.lua. Run tools/gen-manual.sh to
-- regenerate; tests/run-tests.sh fails when the committed manual is stale.
--
-- Usage: tools/gen-manual.lua [source.lua] [output.md]

local src = arg[1] or "script/LaunchControlXL3.lua"
local out = arg[2] or "docs/MANUAL.md"

package.path = "./tests/?.lua;" .. package.path
local mock = require("mock-mpc")
_G.mpc = mock.mpc
_G.dev = mock.dev
_G.LaunchControlXL3 = mock.dev
dofile(os.getenv("LCXL3_LUA") or src)

local L = LaunchControlXL3
local A = L.ACTIONS
assert(type(A) == "table", "the script did not expose ACTIONS")
local P = L.PALETTE
assert(type(P) == "table", "the script did not expose PALETTE")

local lines = {}
local function add(s)
	lines[#lines + 1] = s or ""
end

add("# Launch Control XL 3 controller manual")
add()
add("Generated from `script/LaunchControlXL3.lua` by `tools/gen-manual.sh`.")
add("Do not edit this file: edit the script and regenerate.")
add()
add("## Surface")
add()
add("```")
add("  screen      Page up/down (106/107)   Track </> (103/102)")
add("              Record (118) / Play (116)   Shift (ch7 63) / Mode (ch7 30)")
add("  encoders    rows 1-3, eight each: CC 13-36 absolute / 77-100 relative (ch 16)")
add("  faders      CC 5-12 (ch 16)")
add("  buttons     Solo/Arm row CC 37-44, Mute/Select row CC 45-52 (ch 1)")
add("              far left: Solo/Arm 65, Mute/Select 66; Novation 104")
add("```")
add()

-- group the actions, preserving first-seen order
local order, groups = {}, {}
for _, a in ipairs(A) do
	if not groups[a.group] then
		groups[a.group] = {}
		order[#order + 1] = a.group
	end
	groups[a.group][#groups[a.group] + 1] = a
end

for _, g in ipairs(order) do
	add("## " .. g)
	add()
	add("| CC | Control | Press | Shift + press |")
	add("|----|---------|-------|---------------|")
	for _, a in ipairs(groups[g]) do
		add(string.format("| %d | %s | %s | %s |", a.cc, a.label, a.plain, a.shift))
	end
	add()
end

add("## Modes")
add()
add("- **DAW Mixer** (device mode 1): rows 1/2 = Send 1/2 per track, row 3 = Pan.")
add("  Page up/down switches the send bank (1+2 / 3+4).")
add("- **DAW Control** (device mode 2): rows 1/2 = MPC Q-Links 0-15, hardware-")
add("  routed through `AddInfiniteCCToQLink` (script-side `Twist` fallback when the")
add("  mapping API is missing). Row 3 = global parameters (tempo, swing, quantize")
add("  strength, quantize division, metronome, loop, automation filter, master")
add("  volume); Page up/down cycles row 3 global/track, Shift+Page walks plugin presets.")
add("- **Custom modes** (device modes 6-29): the surface belongs to the device; the")
add("  script keeps transport and navigation alive and shows the mode on screen.")
add()
add("## Faders and pickup")
add()
add("Faders write `normalTracks[bank+col].Volume`. On load and on every bank move the")
add("script pushes each track's volume to the device (CC 5-12 on MIDI ch 16) so the")
add("hardware pickup can suppress jumps, and arms a software pickup that ignores")
add("movement until the fader reaches or crosses the track's value.")
add()
add("## Colours")
add()
add("LEDs use custom RGB (sysex op 01 53h): the dim states are genuinely dark,")
add("so on/off contrast is high regardless of the DAW-mode palette.")
add()
add("| Name | RGB |")
add("|------|-----|")
for _, name in ipairs({ "off", "whiteDim", "white", "red", "redDim", "green", "greenDim", "blue", "blueDim", "orange", "orangeDim", "yellow", "purple", "turquoise", "darkBlue" }) do
	local v = P[name]
	if v then
		add(string.format("| %s | %d, %d, %d |", name, v[1], v[2], v[3]))
	end
end
add()
add("## Journal")
add()
add("Every action logs a line through `print`, prefixed `LaunchControlXL3:`.")
add("Read it with:")
add()
add("```sh")
add("journalctl -u acvs -o cat --no-pager | grep LaunchControlXL3")
add("```")
add()
add("## Guards")
add()
add("Project-scoped actions refuse to run while no project is loaded or a dialog")
add("owns the UI (`engineMode.CurrentPopup` is not `No Popup`). Each refusal logs")
add("once. Missing APIs (Q-Link mapping, sequencer, tracks) disable their surface")
add("and never crash the host app.")
add()

local fh = assert(io.open(out, "w"))
fh:write(table.concat(lines, "\n"))
fh:close()
io.write("gen-manual: wrote " .. out .. "\n")
